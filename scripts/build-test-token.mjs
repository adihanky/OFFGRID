import solc from 'solc';
import { readFileSync, writeFileSync } from 'node:fs';
const source = readFileSync('contracts/OffgridTestToken.sol', 'utf8');
const output = JSON.parse(
  solc.compile(
    JSON.stringify({
      language: 'Solidity',
      sources: { 'OffgridTestToken.sol': { content: source } },
      settings: {
        optimizer: { enabled: true, runs: 200 },
        evmVersion: 'shanghai',
        outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } },
      },
    }),
    { import: (path) => ({ contents: readFileSync(`node_modules/${path}`, 'utf8') }) },
  ),
);
for (const error of output.errors ?? [])
  if (error.severity === 'error') throw new Error(error.formattedMessage);
const token = output.contracts['OffgridTestToken.sol'].OffgridTestToken;
writeFileSync(
  'apps/web/src/test-token-artifact.ts',
  `// Generated by npm run build:test-token from contracts/OffgridTestToken.sol; do not edit.\nexport const testTokenBytecode = '0x${token.evm.bytecode.object}';\n`,
);
console.log('Compiled test-only ERC-20 with solc ' + solc.version());
